"""Independent Python model of the hemera permutation, sponge and modes.

Two profiles:

- 0.4 (the frozen profile): x^7 in every round, R_F 6 + 6, R_P 48, external
  4x4 block of the Poseidon2 reference (Horizen Labs), internal diagonal of
  the Poseidon2 reference instance for Goldilocks t = 16, 240 constants
  self-bootstrapped from the seed "cyber" and accepted by the checks of
  `poseidon2_params.py`.
- 0.3 (the record): x^7 full rounds 4 + 4, x^-1 partial rounds 16, the
  Plonky3 circulant 4x4 block circ(2, 3, 1, 1), 144 bootstrapped constants.

Nothing is read from the Rust crate to compute an output: the model derives
every constant itself (bootstrap) and only compares against the Rust tables
and the vector file. `python3 hemera_ref.py` checks:

1. the generic permutation against the Horizen Labs / Plonky3 width-8
   Goldilocks test vectors (constants regenerated by the Grain LFSR of
   `poseidon2_params.py`) — the model is Poseidon2;
2. the 0.4 bootstrap against `rs/src/constants.rs` and the table printed
   in `specs/constants.md` (all 240 values);
3. every 0.4 entry of `vectors/hemera.json` (permutation, hash, keyed_hash,
   derive_key, xof, hash_leaf, hash_node, root_hash, fixed_chunk_root) and
   every entry of its "0.3" section;
4. the CDC gear table of `rs/src/cdc.rs` (256 hashes of single bytes).
"""
import sys, os, re, json

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from poseidon2_params import (P, M4_HL, M4_PLONKY3, DIAG16, constant_checks,
                              grain_constants, HL8_VECTORS, DIAG8)

_ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
GENESIS_SEED = bytes([0x63, 0x79, 0x62, 0x65, 0x72])   # "cyber"


# ── permutation ──────────────────────────────────────────────────────

def inv(x):
    return pow(x, P - 2, P) if x % P else 0


def mat4(m, x):
    return [sum(m[r][c] * x[c] for c in range(4)) % P for r in range(4)]


def m_e(s, m4):
    """External layer circ(2*M4, M4, ..., M4) for t = 4k (Poseidon2 §5.1)."""
    t = len(s)
    out = []
    for j in range(t // 4):
        out.extend(mat4(m4, s[4*j:4*j+4]))
    sums = [sum(out[j*4 + k] for j in range(t // 4)) % P for k in range(4)]
    return [(out[i] + sums[i % 4]) % P for i in range(t)]


def m_i(s, diag):
    """Internal layer 1 + diag(d): s'_i = d_i s_i + sum(s)."""
    total = sum(s) % P
    return [(diag[i] * s[i] + total) % P for i in range(len(s))]


class Profile:
    def __init__(self, name, rf_half, rp, partial, m4, diag, width=16):
        self.name, self.rf_half, self.rp = name, rf_half, rp
        self.partial, self.m4, self.diag, self.width = partial, m4, diag, width
        self.n_external = 2 * rf_half * width
        self.n_constants = self.n_external + rp
        self.rc = None                      # set by bootstrap / assignment

    def permute(self, s, rc=None):
        rc = self.rc if rc is None else rc
        t, h = self.width, self.rf_half
        ext, intl = rc[:self.n_external], rc[self.n_external:]
        s = m_e([x % P for x in s], self.m4)
        for r in range(h):
            s = [pow((s[i] + ext[r*t + i]) % P, 7, P) for i in range(t)]
            s = m_e(s, self.m4)
        for j in range(self.rp):
            x = (s[0] + intl[j]) % P
            s[0] = inv(x) if self.partial == 'inv' else pow(x, 7, P)
            s = m_i(s, self.diag)
        for r in range(h, 2 * h):
            s = [pow((s[i] + ext[r*t + i]) % P, 7, P) for i in range(t)]
            s = m_e(s, self.m4)
        return s


V04 = Profile('0.4', 6, 48, 'pow7', M4_HL, DIAG16)
V03 = Profile('0.3', 4, 16, 'inv', M4_PLONKY3, DIAG16)


# ── sponge and modes (specs/sponge.md, specs/capacity.md, specs/tree.md) ──

RATE, RATE_BYTES, OUT = 8, 56, 4
DOMAIN_HASH, DOMAIN_KEYED, DOMAIN_CTX, DOMAIN_MAT = 0, 1, 2, 3
FLAG_ROOT, FLAG_PARENT, FLAG_CHUNK = 1, 2, 4
CHUNK_SIZE = 4096


def encode(block56):
    return [int.from_bytes(block56[7*i:7*i+7] + b'\0', 'little') for i in range(8)]


def limbs_to_bytes(limbs):
    return b''.join((x % P).to_bytes(8, 'little') for x in limbs)


def bytes_to_limbs(b):
    return [int.from_bytes(b[8*i:8*i+8], 'little') for i in range(len(b) // 8)]


class Sponge:
    """Hasher: state[11] = domain, 7-byte limbs added into the rate, final
    block tail || 0x01 || 0*, state[10] = absorbed length (overwrite)."""

    def __init__(self, prof, domain=DOMAIN_HASH, state=None):
        self.prof = prof
        self.s = [0] * 16 if state is None else list(state)
        if state is None:
            self.s[11] = domain
        self.buf = b''
        self.absorbed = 0

    def update(self, data):
        self.absorbed += len(data)
        self.buf += data
        while len(self.buf) >= RATE_BYTES:
            blk = encode(self.buf[:RATE_BYTES])
            self.buf = self.buf[RATE_BYTES:]
            self.s = [(self.s[i] + blk[i]) % P if i < 8 else self.s[i] for i in range(16)]
            self.s = self.prof.permute(self.s)
        return self

    def finalize_state(self):
        tail = self.buf + b'\x01'
        blk = encode(tail + b'\0' * (RATE_BYTES - len(tail)))
        s = [(self.s[i] + blk[i]) % P if i < 8 else self.s[i] for i in range(16)]
        s[10] = self.absorbed
        return self.prof.permute(s)

    def finalize(self):
        return limbs_to_bytes(self.finalize_state()[:OUT])

    def xof(self, nbytes):
        s, out = self.finalize_state(), b''
        while len(out) < nbytes:
            out += limbs_to_bytes(s[:OUT])
            s = self.prof.permute(s)
        return out[:nbytes]


def hash_bytes(prof, msg):
    return Sponge(prof).update(msg).finalize()


def keyed_hash(prof, key32, msg):
    return Sponge(prof, DOMAIN_KEYED).update(key32).update(msg).finalize()


def derive_key(prof, context, material):
    ctx = Sponge(prof, DOMAIN_CTX).update(context).finalize()
    s = [0] * 16
    s[:4] = bytes_to_limbs(ctx)
    s[11] = DOMAIN_MAT
    s = prof.permute(s)
    return Sponge(prof, state=s).update(material).finalize()


def hash_leaf(prof, chunk, counter, root):
    base = hash_bytes(prof, chunk)
    s = [0] * 16
    s[:4] = bytes_to_limbs(base)
    s[8] = counter
    s[9] = FLAG_CHUNK | (FLAG_ROOT if root else 0)
    return limbs_to_bytes(prof.permute(s)[:OUT])


def hash_node(prof, left, right, root):
    s = [0] * 16
    s[:4] = bytes_to_limbs(left)
    s[4:8] = bytes_to_limbs(right)
    s[9] = FLAG_PARENT | (FLAG_ROOT if root else 0)
    return limbs_to_bytes(prof.permute(s)[:OUT])


def _split(count):
    return 1 << ((count - 1).bit_length() - 1)


def merge(prof, leaves, root):
    if len(leaves) == 1:
        return leaves[0]
    k = _split(len(leaves))
    return hash_node(prof, merge(prof, leaves[:k], False), merge(prof, leaves[k:], False), root)


def fixed_chunk_root(prof, data):
    n = max(1, -(-len(data) // CHUNK_SIZE))
    if n == 1:
        return hash_leaf(prof, data, 0, True)
    leaves = [hash_leaf(prof, data[i*CHUNK_SIZE:(i+1)*CHUNK_SIZE], i, False) for i in range(n)]
    return merge(prof, leaves, True)


def gear_table(prof):
    return [int.from_bytes(hash_bytes(prof, bytes([i]))[:8], 'little') for i in range(256)]


def root_hash(prof, data, gear=None):
    """CDC tree, element size 1 (rs/src/cdc.rs section_cdc_tree): window 4096,
    chunks of 2048..8192 bytes cut after the first minimum gear value."""
    n = len(data)
    if n == 0:
        return hash_leaf(prof, b'', 0, True)
    gear = gear or gear_table(prof)
    lo_len, hi_len = 2048, 8192
    bounds, last = [0], 0
    while last < n:
        lo = last + lo_len - 1
        hi = min(last + hi_len - 1, n - 1)
        if lo > n - 1:
            bounds.append(n)
            break
        best = min(range(lo, hi + 1), key=lambda i: (gear[data[i]], i))
        bounds.append(best + 1)
        last = best + 1
    if len(bounds) == 2:
        return hash_leaf(prof, data, 0, True)
    leaves = [hash_leaf(prof, data[bounds[i]:bounds[i+1]], i, False) for i in range(len(bounds) - 1)]
    return merge(prof, leaves, True)


# ── constants: self-bootstrap (specs/bootstrap.md) ──────────────────

def squeeze_constants(prof, seed):
    """Hemera_0 (all constants 0) absorbs `seed` as a plain-hash sponge
    (domain 0, pad 0x01, state[10] = len) and squeezes n_constants
    elements, 8 per permutation."""
    zero = [0] * prof.n_constants
    assert len(seed) < RATE_BYTES
    s = [0] * 16
    blk = encode(seed + b'\x01' + b'\0' * (RATE_BYTES - len(seed) - 1))
    for i in range(8):
        s[i] = blk[i]
    s[10] = len(seed)
    s = prof.permute(s, zero)
    out, pos = [], 0
    for _ in range(prof.n_constants):
        if pos == RATE:
            s = prof.permute(s, zero)
            pos = 0
        out.append(s[pos])
        pos += 1
    return out


def bootstrap(prof, checked=True):
    """Counter k = 0, 1, ...: seed_0 = GENESIS_SEED, seed_k = GENESIS_SEED || k
    (one byte). The first constant set that passes the checks is taken.
    0.3 had no checks (checked=False reproduces it)."""
    for k in range(256):
        seed = GENESIS_SEED if k == 0 else GENESIS_SEED + bytes([k])
        rc = squeeze_constants(prof, seed)
        if not checked:
            return rc, 0, None
        report = constant_checks(rc)
        if all(ok for _, ok in report):
            return rc, k, report
    raise RuntimeError('no constant set passed the checks')


def rust_table(path, start, end=']'):
    src = open(os.path.join(_ROOT, path)).read()
    body = src[src.index(start):]
    body = body[:body.index(end + ';')]
    body = re.sub(r'//[^\n]*', '', body)
    return [int(x, 16) for x in re.findall(r'0x([0-9A-Fa-f_]+)', body.replace('_', ''))]


V03.rc, _, _ = bootstrap(V03, checked=False)
V04.rc, V04_COUNTER, V04_REPORT = bootstrap(V04)

# Backwards-compatible names for audit/campaign/cico1.py (the 0.3 record).
RC, DIAG = V03.rc, DIAG16


def permute(s, rc=None, rf_half=4, rp=16, partial='inv'):
    """0.3-shaped permutation with optional reduced rounds (cico1.py): the
    first rf_half and the last rf_half external rows of `rc` are used."""
    rc = V03.rc if rc is None else rc
    prof = Profile('reduced', rf_half, rp, partial, M4_PLONKY3, DIAG16)
    ext = rc[:4*16]
    ext = ext[:rf_half*16] + rc[4*16:4*16 + rf_half*16]
    return prof.permute(s, ext + rc[128:128 + rp])


# ── self-check ──────────────────────────────────────────────────────

def _hex(b):
    return b.hex()


def check_vectors(prof, vec, cdc_gear):
    bad = 0

    def eq(name, got, want):
        nonlocal bad
        if got != want:
            bad += 1
            print(f'  MISMATCH {prof.name} {name}: model {got} file {want}')

    for name, want in vec.get('hash', {}).items():
        msg = {'empty': b'', 'hello': b'hello', 'hemera': b'hemera'}.get(name)
        if msg is None:
            msg = bytes.fromhex(vec['inputs'][name])
        eq('hash/' + name, _hex(hash_bytes(prof, msg)), want)
    for name, want in vec.get('tree', {}).items():
        msg = {'empty': b'', 'hello': b'hello', '4k_zeros': bytes(4096)}[name]
        eq('tree/' + name, _hex(fixed_chunk_root(prof, msg)), want)
    for name, want in vec.get('derive_key', {}).items():
        assert name == 'test'
        eq('derive_key/test', _hex(derive_key(prof, b'test context', b'test material')), want)
    for e in vec.get('permutation', []):
        eq('permutation/' + e['name'], ['%016x' % x for x in prof.permute([int(x, 16) for x in e['input']])],
           e['output'])
    for e in vec.get('keyed_hash', []):
        eq('keyed_hash/' + e['name'], _hex(keyed_hash(prof, bytes.fromhex(e['key']), bytes.fromhex(e['input']))),
           e['output'])
    for e in vec.get('derive_key_cases', []):
        eq('derive_key/' + e['name'], _hex(derive_key(prof, e['context'].encode(), bytes.fromhex(e['material']))),
           e['output'])
    for e in vec.get('xof', []):
        out = Sponge(prof).update(bytes.fromhex(e['input'])).xof(len(e['output']) // 2)
        eq('xof/' + e['name'], _hex(out), e['output'])
    for e in vec.get('hash_leaf', []):
        eq('hash_leaf/' + e['name'],
           _hex(hash_leaf(prof, bytes.fromhex(e['input']), e['counter'], e['root'])), e['output'])
    for e in vec.get('hash_node', []):
        eq('hash_node/' + e['name'],
           _hex(hash_node(prof, bytes.fromhex(e['left']), bytes.fromhex(e['right']), e['root'])), e['output'])
    for e in vec.get('fixed_chunk_root', []):
        data = bytes([e['fill']]) * e['len']
        eq('fixed_chunk_root/' + e['name'], _hex(fixed_chunk_root(prof, data)), e['output'])
    for e in vec.get('root_hash', []):
        data = bytes((i * e['mul'] + e['add']) & 0xFF for i in range(e['len']))
        eq('root_hash/' + e['name'], _hex(root_hash(prof, data, cdc_gear)), e['output'])
    return bad


def hl_width8_check():
    """The generic model at t = 8 with the Horizen Labs constants (regenerated
    by Grain) and matrices reproduces the HL/Plonky3 test vectors."""
    rc = grain_constants(8, 8, 22)
    # HL layout: 4 rows external, 22 internal, 4 rows external.
    ext = rc[:32] + rc[32 + 22:32 + 22 + 32]
    prof = Profile('hl8', 4, 22, 'pow7', M4_HL, DIAG8, width=8)
    return all(prof.permute(i, ext + rc[32:54]) == o for i, o in HL8_VECTORS)


